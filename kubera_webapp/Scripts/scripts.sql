-- DROP SCHEMA management;

CREATE SCHEMA management AUTHORIZATION "admin";

-- ============================================
-- Brokers
-- ============================================
CREATE TABLE management.brokers (
	Id serial NOT NULL,
	Code int NOT NULL,
	Name varchar NULL,
	Document varchar NULL,
	ContractDate date NULL,
	Status bool DEFAULT true NOT NULL,
	BillingCurrency varchar NULL,
	Contacts text[] NULL,
	CONSTRAINT brokers_pk PRIMARY KEY (Id)
);

-- ============================================
-- Process Billing (controle de jobs)
-- ============================================
CREATE TABLE management.process_billing (
	ProcessId int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	ProcessDate date NOT NULL,
	Status varchar NOT NULL,
	ProcessBroker varchar NOT NULL,
	LockedAt timestamp NULL,
	CONSTRAINT process_billing_pk PRIMARY KEY (ProcessId)
);

CREATE INDEX idx_process_billing_status ON management.process_billing(Status);
