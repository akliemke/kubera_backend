-- DROP SCHEMA management;

CREATE SCHEMA management AUTHORIZATION "admin";



CREATE TABLE management.brokers (
	id serial NOT NULL,
	code varchar NOT NULL,
	"name" varchar NULL,
	nickname varchar NOT NULL,
	"document" varchar NULL,
	contract_date date NOT NULL,
	status bool DEFAULT true NOT NULL,
	CONSTRAINT brokers_pk PRIMARY KEY (id)
);


CREATE TABLE management.billing_process (
	process_id int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	billing_date date NOT NULL,
	status varchar NOT NULL,
	brokers_to_process varchar NOT NULL,
	process_timestamp timestamp NOT NULL,
	locked_at timestamp NULL,  -- Timestamp de quando o processamento foi iniciado (para lock)
	CONSTRAINT billing_process_pk PRIMARY KEY (process_id)
);

CREATE INDEX idx_billing_process_status ON management.billing_process(status);

