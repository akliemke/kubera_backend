-- DROP SCHEMA management;

CREATE SCHEMA management AUTHORIZATION "admin";

-- ============================================
-- Brokers
-- ============================================
CREATE TABLE management.brokers (
	Id serial NOT NULL,
	Code int NOT NULL,
	Name varchar NULL,
	Document varchar NULL,
	ContractDate date NULL,
	Status bool DEFAULT true NOT NULL,
	BillingCurrency varchar NULL,
	Contacts text[] NULL,
	CONSTRAINT brokers_pk PRIMARY KEY (Id)
);

-- ============================================
-- Process Billing (controle de jobs)
-- ============================================
CREATE TABLE management.process_billing (
	ProcessId int GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	ProcessDate date NOT NULL,
	Status varchar NOT NULL,
	ProcessBroker varchar NOT NULL,
	LockedAt timestamp NULL,
	CONSTRAINT process_billing_pk PRIMARY KEY (ProcessId)
);

CREATE INDEX idx_process_billing_status ON management.process_billing(Status);

-- ============================================
-- GTC/GTD Support: TimeInForce + trades table + billable orders view
-- ============================================

-- Add TimeInForce column to orders (nullable, existing rows default to NULL = passthrough)
ALTER TABLE history.orders ADD COLUMN IF NOT EXISTS TimeInForce VARCHAR(10) NULL;

-- Trades table (defensive - may already exist in production)
CREATE TABLE IF NOT EXISTS history.trades (
    Id BIGSERIAL PRIMARY KEY,
    OrderId BIGINT NOT NULL,
    LastQty DECIMAL(18,4) NOT NULL,
    LastPx DECIMAL(18,6) NOT NULL,
    Symbol VARCHAR(50) NOT NULL,
    ExchangeSymbol VARCHAR(50),
    AssetClass VARCHAR(20) NOT NULL,
    EnteringTrader VARCHAR(100) NOT NULL,
    Entity VARCHAR(100) NOT NULL,
    TradeDate DATE NOT NULL,
    EnteringFirm VARCHAR(20) NOT NULL,
    OmsInstance VARCHAR(50) NOT NULL,
    Side VARCHAR(10) NOT NULL,
    businessDate VARCHAR(20) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_trades_orderid_date ON history.trades(OrderId, businessDate);

-- View: billable orders (handles GTC/GTD by aggregating daily trades)
CREATE OR REPLACE VIEW history.vw_billable_orders AS

-- Non-GTC/GTD or non-EQUITY: passthrough
SELECT Id, CumQty, AvgPx, Symbol, ExchangeSymbol, AssetClass,
       EnteringTrader, Entity, TradeDate, EnteringFirm, OmsInstance, Side,
       businessDate, TimeInForce
FROM history.orders
WHERE TimeInForce IS NULL
   OR TimeInForce NOT IN ('GTC', 'GTD')
   OR AssetClass != 'EQUITY'

UNION ALL

-- GTC/GTD EQUITY: aggregate trades of the day (VWAP)
SELECT o.Id,
       SUM(t.LastQty) as CumQty,
       SUM(t.LastQty * t.LastPx) / SUM(t.LastQty) as AvgPx,
       o.Symbol, o.ExchangeSymbol, o.AssetClass,
       o.EnteringTrader, o.Entity, o.TradeDate, o.EnteringFirm,
       o.OmsInstance, o.Side, o.businessDate, o.TimeInForce
FROM history.orders o
INNER JOIN history.trades t ON t.OrderId = o.Id AND t.businessDate = o.businessDate
WHERE o.TimeInForce IN ('GTC', 'GTD')
  AND o.AssetClass = 'EQUITY'
GROUP BY o.Id, o.Symbol, o.ExchangeSymbol, o.AssetClass,
         o.EnteringTrader, o.Entity, o.TradeDate, o.EnteringFirm,
         o.OmsInstance, o.Side, o.businessDate, o.TimeInForce;
