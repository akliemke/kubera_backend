CREATE INDEX idx_bracket_fee_tracking_daily ON financial_engine.bracket_fee_tracking(DailyBillingId);
CREATE INDEX idx_bracket_fee_tracking_bracket ON financial_engine.bracket_fee_tracking(BracketId);

